"""
Typed schemas shared by the FastAPI layer, the LangGraph state, and the
individual agents. Keeping these in one place stops each agent inventing
its own ad-hoc dict shape, which is how multi-agent systems rot.
"""
from __future__ import annotations

from enum import Enum
from typing import Any, Literal, Optional

from pydantic import BaseModel, Field


class RequestKind(str, Enum):
    DOCUMENT = "document"      # a filing/order/affidavit was just ingested
    HEARING = "hearing"        # a hearing audio/video/transcript was ingested
    QUESTION = "question"      # free-form question about a case


class IngestResponse(BaseModel):
    case_id: str
    doc_id: str
    modality: str
    chunks_indexed: int
    message: str


class AskRequest(BaseModel):
    case_id: str
    question: str
    top_k: int = 6


class Citation(BaseModel):
    doc_id: str
    source: Literal["case_file", "indian_kanoon", "hearing_transcript"]
    title: Optional[str] = None
    snippet: Optional[str] = None
    url: Optional[str] = None


class ExtractedEntities(BaseModel):
    parties: list[str] = Field(default_factory=list)
    dates: list[str] = Field(default_factory=list)
    statutes_cited: list[str] = Field(default_factory=list)
    court: Optional[str] = None
    case_number: Optional[str] = None


class DocumentAnalysis(BaseModel):
    doc_id: str
    entities: ExtractedEntities
    clause_summary: list[str] = Field(default_factory=list)
    raw_notes: str = ""


class HearingMinutes(BaseModel):
    doc_id: str
    issues_argued: list[str] = Field(default_factory=list)
    submissions: dict[str, list[str]] = Field(default_factory=dict)  # counsel -> points
    court_observations: list[str] = Field(default_factory=list)
    raw_transcript_excerpt: str = ""


class PrecedentResult(BaseModel):
    ik_doc_id: str
    title: str
    court: Optional[str] = None
    date: Optional[str] = None
    relevance_snippet: str
    url: Optional[str] = None


class LegalResearchResult(BaseModel):
    query: str
    precedents: list[PrecedentResult] = Field(default_factory=list)
    notes: str = ""


class FinalBrief(BaseModel):
    case_id: str
    summary: str
    key_issues: list[str] = Field(default_factory=list)
    supporting_precedent: list[PrecedentResult] = Field(default_factory=list)
    citations: list[Citation] = Field(default_factory=list)
    disclaimer: str = (
        "This is an informational brief generated by paraAI for review by a "
        "qualified paralegal or attorney. It is not legal advice."
    )


class GraphState(BaseModel):
    """
    Shared state threaded through every LangGraph node. Nodes read what
    they need and write their own slice back; the router decides which
    nodes run based on `kind`.
    """
    case_id: str
    kind: RequestKind
    question: Optional[str] = None
    raw_input_path: Optional[str] = None
    modality: Optional[str] = None

    retrieved_context: list[dict[str, Any]] = Field(default_factory=list)
    document_analysis: Optional[DocumentAnalysis] = None
    hearing_minutes: Optional[HearingMinutes] = None
    research: Optional[LegalResearchResult] = None
    final_brief: Optional[FinalBrief] = None

    class Config:
        arbitrary_types_allowed = True
